// 민법상 성년은 만 19세. 생년월일을 모르면 미성년으로 보지 않는다(관리자가 동의받을 분을 직접 고른다).
export function isMinor(birth: string | null | undefined, today: string): boolean {
  if (!birth || !/^\d{4}-\d{2}-\d{2}$/.test(birth)) return false;
  const [by, bm, bd] = birth.split("-").map(Number);
  const [ty, tm, td] = today.split("-").map(Number);
  let age = ty - by;
  if (tm < bm || (tm === bm && td < bd)) age--;
  return age < 19;
}

